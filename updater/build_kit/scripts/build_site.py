#!/usr/bin/env python3
"""Build the deployable CME Calendar PWA (Design E) into <out>/.
Usage: python3 -I build_site.py <src_dir> <conferences.json from build_data.py> <out_dir> YYYY-MM-DD
Static output: index.html, styles.css, app.js, sw.js, manifest.webmanifest, icons, fonts/, img/, conferences.json, .nojekyll
Pass the run date explicitly in scheduled runs; it stamps the data and the service-worker cache version."""
import sys, os, json, shutil, datetime as dt, hashlib

src, data_path, out, run = sys.argv[1:5]
d = dt.date.fromisoformat(run)
asof = f"{d:%B} {d.day}, {d.year}"
rows = json.load(open(data_path, encoding="utf-8"))

KEEP = ["id", "name", "society", "specialty", "precision", "start", "end", "year", "month", "dates", "location", "city",
        "format", "url", "status", "verified", "verified_on", "verification", "notes"]
slim = [{k: r.get(k) for k in KEEP} for r in rows]
assert len(slim) == len(rows)

if os.path.exists(out):
    shutil.rmtree(out)
shutil.copytree(src, out)
payload = {"asOf": asof, "asOfIso": run, "count": len(slim), "entries": slim}
open(f"{out}/conferences.json", "w", encoding="utf-8").write(json.dumps(payload, ensure_ascii=False, separators=(",", ":")))

json.dump({
    "name": "CME Calendar", "short_name": "CME Calendar",
    "description": "Verified calendar of upcoming CME conferences worldwide.",
    "start_url": "./", "scope": "./", "id": "./", "display": "standalone",
    "background_color": "#EFE9F9", "theme_color": "#34195F", "orientation": "portrait-primary",
    "icons": [
        {"src": "icon-192.png", "sizes": "192x192", "type": "image/png", "purpose": "any"},
        {"src": "icon-512.png", "sizes": "512x512", "type": "image/png", "purpose": "any"},
        {"src": "icon-192.png", "sizes": "192x192", "type": "image/png", "purpose": "maskable"},
        {"src": "icon-512.png", "sizes": "512x512", "type": "image/png", "purpose": "maskable"}],
}, open(f"{out}/manifest.webmanifest", "w"), indent=1)

# service worker: version = run date + hash of the shell files, so any change refreshes the cache
shell = ["./", "index.html", "styles.css", "app.js", "manifest.webmanifest", "icon-192.png", "icon-512.png",
         "img/stage.webp", "img/panel.webp", "img/workshop.webp", "img/boardroom.webp",
         "fonts/pjs-500.woff2", "fonts/pjs-600.woff2", "fonts/pjs-700.woff2", "fonts/pjs-800.woff2", "conferences.json"]
h = hashlib.sha1()
for f in sorted(p for p in shell if p != "./"):
    h.update(open(f"{out}/{f}", "rb").read())
ver = f"{run}-{h.hexdigest()[:8]}"
open(f"{out}/sw.js", "w").write("""/* CME Calendar service worker. Generated by build_site.py; do not edit. */
const VERSION = '%s';
const CACHE = 'cme-' + VERSION;
const SHELL = %s;
self.addEventListener('install', e => {
  e.waitUntil(caches.open(CACHE).then(c => Promise.all(SHELL.map(u => c.add(new Request(u, { cache: 'reload' }))))).then(() => self.skipWaiting()));
});
self.addEventListener('activate', e => {
  e.waitUntil(caches.keys().then(ks => Promise.all(ks.filter(k => k.startsWith('cme-') && k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener('fetch', e => {
  const req = e.request, u = new URL(req.url);
  if (req.method !== 'GET' || u.origin !== location.origin) return;
  // data: stale-while-revalidate, so it opens instantly (and offline) and refreshes in the background
  if (u.pathname.endsWith('/conferences.json')) {
    e.respondWith(caches.open(CACHE).then(async c => {
      const hit = await c.match(req, { ignoreSearch: true });
      const net = fetch(req).then(r => { if (r.ok) c.put(req, r.clone()); return r; }).catch(() => hit);
      return hit || net;
    }));
    return;
  }
  // pages: serve the cached shell (offline fallback = index.html)
  if (req.mode === 'navigate') {
    e.respondWith(caches.match('index.html').then(m => m || fetch(req)));
    return;
  }
  // static assets: cache first
  e.respondWith(caches.match(req, { ignoreSearch: true }).then(m => m || fetch(req).then(r => {
    if (r.ok) { const cp = r.clone(); caches.open(CACHE).then(c => c.put(req, cp)); }
    return r;
  })));
});
""" % (ver, json.dumps(shell)))

open(f"{out}/.nojekyll", "w").write("")
print("site built:", out, "| entries", len(slim), "| asOf", asof, "| sw", ver)
