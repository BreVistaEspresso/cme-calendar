/* ---------- date helpers ---------- */
function isPast(e, todayISO, todayYear) {
  if (e.precision === 'exact' || e.precision === 'month') return e.end < todayISO;
  if (e.precision === 'tba') return e.year ? e.year < todayYear : e.status === 'Completed';
  return e.status === 'Completed';
}

function groupInfo(e) {
  if ((e.precision === 'exact' || e.precision === 'month') && e.year && e.month) {
    return { key: `${e.year}-${pad(e.month)}`, label: `${MONTHS[e.month - 1].toUpperCase()} ${e.year}` };
  }
  if (e.precision === 'tba' && e.year) return { key: `${e.year}-13`, label: `${e.year} · DATES TO BE ANNOUNCED` };
  if (e.precision === 'ongoing') return { key: '9998', label: 'ONGOING & ON-DEMAND' };
  return { key: '9999', label: 'DATE NOT YET ANNOUNCED' };
}

/* ---------- ICS export ---------- */
const icsEscape = (s) =>
  String(s || '').replace(/\\/g, '\\\\').replace(/;/g, '\\;').replace(/,/g, '\\,').replace(/\r?\n/g, '\\n');

function foldLine(line) {
  const enc = new TextEncoder();
  if (enc.encode(line).length <= 75) return line;
  const parts = [];
  let cur = '';
  let bytes = 0;
  let limit = 75;
  for (const ch of line) {
    const b = enc.encode(ch).length;
    if (bytes + b > limit) {
      parts.push(cur);
      cur = '';
      bytes = 0;
      limit = 74; // continuation lines start with one space
    }
    cur += ch;
    bytes += b;
  }
  parts.push(cur);
  return parts.join('\r\n ');
}

function icsDate(iso) {
  return iso.replace(/-/g, '');
}
function icsNextDay(iso) {
  const [y, m, d] = iso.split('-').map(Number);
  const n = new Date(Date.UTC(y, m - 1, d + 1));
  return `${n.getUTCFullYear()}${pad(n.getUTCMonth() + 1)}${pad(n.getUTCDate())}`;
}
function icsStamp() {
  const n = new Date();
  return `${n.getUTCFullYear()}${pad(n.getUTCMonth() + 1)}${pad(n.getUTCDate())}T${pad(n.getUTCHours())}${pad(n.getUTCMinutes())}${pad(n.getUTCSeconds())}Z`;
}

function buildICS(events) {
  const stamp = icsStamp();
  const lines = ['BEGIN:VCALENDAR', 'VERSION:2.0', 'PRODID:-//Brevista//Global CME Calendar//EN', 'CALSCALE:GREGORIAN', 'METHOD:PUBLISH', 'X-WR-CALNAME:Global CME Calendar'];
  events.forEach((e) => {
    const desc = [
      `${e.specialty} CME conference.`,
      e.url ? `Official site: ${e.url}` : 'Official link not yet available.',
      e.status === 'Unverified' ? 'Note: dates and location not yet verified. Confirm before booking.' : 'Confirm dates and registration on the official site.',
    ].join('\n');
    lines.push('BEGIN:VEVENT', `UID:cme-${e.id}-${e.start}@global-cme-calendar`, `DTSTAMP:${stamp}`, `DTSTART;VALUE=DATE:${icsDate(e.start)}`, `DTEND;VALUE=DATE:${icsNextDay(e.end || e.start)}`, `SUMMARY:${icsEscape(e.name)}`);
    if (e.location && !/to be announced/i.test(e.location)) lines.push(`LOCATION:${icsEscape(e.location)}`);
    if (e.url) lines.push(`URL:${e.url}`);
    lines.push(`DESCRIPTION:${icsEscape(desc)}`, `CATEGORIES:${icsEscape(e.specialty)}`, 'END:VEVENT');
  });
  lines.push('END:VCALENDAR');
  return lines.map(foldLine).join('\r\n') + '\r\n';
}

function downloadICS(filename, text) {
  const blob = new Blob([text], { type: 'text/calendar;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  setTimeout(() => URL.revokeObjectURL(url), 2000);
}

function gcalUrl(e) {
  const desc = `${e.specialty} CME conference.${e.url ? `\nOfficial site: ${e.url}` : ''}\n${e.status === 'Unverified' ? 'Dates and location not yet verified. Confirm before booking.' : 'Confirm dates and registration on the official site.'}`;
  const q = new URLSearchParams({ action: 'TEMPLATE', text: e.name, dates: `${icsDate(e.start)}/${icsNextDay(e.end || e.start)}`, details: desc });
  if (e.location && !/to be announced/i.test(e.location)) q.set('location', e.location);
  return `https://calendar.google.com/calendar/render?${q.toString()}`;
}

